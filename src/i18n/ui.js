export function t(lang, key, vars = {}) {
  const table = ui[lang] || ui.fr
  let value = table[key] ?? ui.fr[key] ?? key
  if (typeof value !== 'string') return value
  Object.entries(vars).forEach(([k, v]) => {
    value = value.replaceAll(`{${k}}`, String(v))
  })
  return value
}
